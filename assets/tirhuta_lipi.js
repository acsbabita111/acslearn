/* उल्टा नक़्शा (मशीन-निर्मित; ड़/ढ़ का NFC-रूप हाथ से) */
var TIRHUTA_DEVA = {};
(function () {
  for (var k in TIRHUTA_MAP) {
    if (k >= "0" && k <= "9") continue;           /* उल्टे में देवनागरी-अंक ही */
    TIRHUTA_DEVA[TIRHUTA_MAP[k]] = k;
  }
})();

function devaToTirhuta(s) {
  s = String(s).normalize("NFD");                  /* ड़→ड+़, क़→क+़ आदि खुलें */
  var out = "";
  for (var ch of s) out += TIRHUTA_MAP[ch] !== undefined ? TIRHUTA_MAP[ch] : ch;
  return out;                                      /* दंड/विराम/space passthrough */
}
function tirhutaToDeva(s) {
  var out = "";
  for (var ch of String(s)) out += TIRHUTA_DEVA[ch] !== undefined ? TIRHUTA_DEVA[ch] : ch;
  return out.normalize("NFC");
}
