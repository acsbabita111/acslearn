function chrome(lang) {
  let t = rd("_TEMPLATE.html");
  const once = (piece) => { const i = t.indexOf(piece); if (i < 0 || t.indexOf(piece, i + 1) > -1) stop("_TEMPLATE.html में \"" + piece + "\" ठीक एक बार नहीं"); return i; };
  const S = "<!-- PAGE-CONTENT-START -->", E = "<!-- PAGE-CONTENT-END -->";
  once("<title>"); once("</head>"); once('<html lang="hi">'); once("<body>");
  const a = once(S), b = once(E);
  t = t.slice(0, a) + "@@BODY@@" + t.slice(b + E.length);
  t = t.replace(/<title>[\s\S]*?<\/title>/, "@@HEAD@@").replace("</head>", "@@EXTRA@@</head>")
       .replace('<html lang="hi">', '<html lang="' + lang + '">').replace("<body>", '<body data-lang="' + lang + '" data-page="network">')
       .replace("<!DOCTYPE html>", "<!DOCTYPE html>\n" + GEN);
  if (lang !== "hi") {
    const used = new Set(), L = MLG.readLinks();
    t = BML.translate(t, CHROME_EN.T, BML.linkMap(L, lang), used);
    if (BML.DEV.test(t)) stop("English ढाँचे में देवनागरी बची");
  }
  for (const m of ["@@HEAD@@", "@@EXTRA@@", "@@BODY@@"]) if (t.split(m).length !== 2) stop("ढाँचे में " + m + " ठीक एक बार नहीं");
  return t;
}
